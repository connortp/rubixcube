"""Regenerate js/words.js.

Inputs:
  - a dictionary file with one lowercase word per line (we used words.txt from the
    `word-list` npm package, v4.1.0)
  - the `wordfreq` Python package, used to drop obscure words

Usage:
  pip install wordfreq
  python scripts/build_words.py path/to/words.txt > js/words.js
"""
import json
import sys

from wordfreq import zipf_frequency

LENGTHS = (3, 5, 7)
# Minimum Zipf frequency for a word to be accepted as a valid guess / used as an answer.
VALID_MIN = {3: 3.1, 5: 2.3, 7: 2.0}
ANSWER_MIN = {3: 3.6, 5: 3.4, 7: 3.2}

BLOCK = set("""
ass anal anus arse bitch boob boobs butt cock coon crap cum cunt damn dick dildo dyke fag
fags fuck gay gays god hell homo jew jizz kike nazi nigga nigger penis piss porn pussy rape
raped raper rapes semen sex sexy shit slut spic tit tits twat vagina whore wank crack drugs
nude nudes nudity heroin cocaine suicide killer murder hitler rapist slave slaves erotic
breast breasts orgasm virgin virgins sperm testes horny bigot negro negros pervert
""".split())


# Names, abbreviations and fragments that sneak into dictionaries. Never count these.
NOT_WORDS = set("""
aka alt ana ann ave ben bio bon cos dan das dee def del dev dis dos dow eds eng est gen geo
gif gov gus han hes ing ins ios ish iso jin joe jun kai kat kay lee les lib lin los lou mae
mar med mel mic mil mon nam nat ned pac pam pic pos pre rec reg rep res rev rex sam san sec
sen sim sis sox sri sur ted tel tho til uni var vol
""".split())

# Real but odd words (slang, interjections, jargon) that are fine to score but too
# obscure to be one of the day's hidden words.
ANSWER_SKIP = set("""
bot cha chi col con cuz dom don doo duh heh hmm hon huh nah non ole ops sac sic sol tis
ugh yep yup ken
""".split())


def main(path):
    words = set()
    with open(path) as f:
        for line in f:
            w = line.strip()
            if w.isalpha() and w.isascii() and len(w) in LENGTHS:
                words.add(w)
    valid = {n: [] for n in LENGTHS}
    answers = {n: [] for n in LENGTHS}
    for w in sorted(words):
        n = len(w)
        if w in BLOCK or w in NOT_WORDS:
            continue
        z = zipf_frequency(w, "en")
        if z >= VALID_MIN[n]:
            valid[n].append(w)
            if z >= ANSWER_MIN[n] and w not in ANSWER_SKIP:
                answers[n].append(w)
    out = ["// Generated by scripts/build_words.py. Do not edit by hand."]
    for n in LENGTHS:
        out.append(f"// {len(answers[n])} answers / {len(valid[n])} valid {n}-letter words")
    out.append("export const ANSWERS = " + json.dumps({n: " ".join(answers[n]).upper() for n in LENGTHS}) + ";")
    out.append("export const VALID = " + json.dumps({n: " ".join(valid[n]).upper() for n in LENGTHS}) + ";")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
